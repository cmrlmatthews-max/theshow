// Builds src/geo.js: US states (lower 48 + DC) and neighbor countries, as compact GeoJSON.
import fs from 'fs';
import { feature, mesh } from 'topojson-client';
const us = JSON.parse(fs.readFileSync('node_modules/us-atlas/states-10m.json'));
const world = JSON.parse(fs.readFileSync('node_modules/world-atlas/countries-50m.json'));
const skip = new Set(['02','15','60','66','69','72','78']);
us.objects.states.geometries = us.objects.states.geometries.filter(g => !skip.has(g.id));
const round = (c) => [Math.round(c[0]*100)/100, Math.round(c[1]*100)/100];
const dedupe = (ring) => { const out=[]; for (const p of ring.map(round)) { const l=out[out.length-1]; if(!l||l[0]!==p[0]||l[1]!==p[1]) out.push(p);} return out; };
function clean(geom, keep) {
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  const out = [];
  for (const poly of polys) {
    const ring = poly[0];
    let minLat=90,maxLat=-90,minLon=180,maxLon=-180;
    for (const [x,y] of ring){ if(y<minLat)minLat=y; if(y>maxLat)maxLat=y; if(x<minLon)minLon=x; if(x>maxLon)maxLon=x; }
    if (keep && !keep({minLat,maxLat,minLon,maxLon})) continue;
    const rings = poly.map(dedupe).filter(r => r.length >= 4);
    if (rings.length) out.push(rings);
  }
  return { type: 'MultiPolygon', coordinates: out };
}
const states = feature(us, us.objects.states).features.map(f => ({ type:'Feature', id:f.id, properties:{name:f.properties.name}, geometry: clean(f.geometry) }));
const borders = mesh(us, us.objects.states, (a,b)=>a!==b);
borders.coordinates = borders.coordinates.map(l => l.map(round));
const nationGeom = feature(us, us.objects.nation ?? us.objects.states);
const countries = feature(world, world.objects.countries).features;
const pick = (id, keep) => { const f = countries.find(c => c.id === id); return { type:'Feature', id, properties:{name:f.properties.name}, geometry: clean(f.geometry, keep) }; };
const neighbors = [
  pick('124', b => b.minLat < 62 && b.maxLon > -141),   // Canada, without the high Arctic
  pick('484'),                                          // Mexico
  pick('192'), pick('044')                              // Cuba, Bahamas
];
const out = `// Generated by build-geo.mjs. Sources: us-atlas (US Census Bureau), world-atlas (Natural Earth).\nexport const STATES = ${JSON.stringify(states)};\nexport const NEIGHBORS = ${JSON.stringify(neighbors)};\n`;
fs.writeFileSync('src/geo.js', out);
console.log('states', states.length, 'bytes', out.length);
