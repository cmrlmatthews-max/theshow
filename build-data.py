# Merges the six division files, applies the fact-check corrections, writes data/stadiums.json and src/data.js
import json, glob
CLEM = "https://andrewclem.com/Baseball/Stadium_statistics.html"
recs = {}
for f in sorted(glob.glob('data/raw/*.json')):
    for r in json.load(open(f)): recs[r['id']] = r

# 1. Wall heights (LF, CF, RF) from Clem's Baseball, used only where the first pass found no value.
clem = {'DET':(7,9,9),'KC':(9,9,9),'MIN':(8,8,23),'BOS':(37,18,5),'NYY':(8,8,8),'TBR':(11,9,11),'HOU':(21,9,7),
        'LAA':(5,8,18),'SEA':(15,7,7),'CIN':(12,8,8),'MIL':(8,8,8),'STL':(8,8,8),'ATL':(6,8,16),'MIA':(10,15,10),
        'NYM':(8,8,8),'PHI':(11,6,13),'WSH':(10,12,9),'COL':(8,8,17),'LAD':(4,8,4),'SD':(4,7,10),'BAL':(7,7,21)}
for k,(a,b,c) in clem.items():
    w = recs[k]['wall_ft']; used = False
    for key,v in (('lf',a),('cf',b),('rf',c)):
        if w.get(key) is None: w[key] = v; used = True
    if used and CLEM not in recs[k]['sources']: recs[k]['sources'].append(CLEM)
# Camden Yards: left-field wall changed for 2025; first-pass value was from 2022.
recs['BAL']['wall_ft'] = {'lf':7,'cf':7,'rf':21}
# Rogers Centre: walls changed in the 2023 renovation. Approximate; listed in README "values to verify".
recs['TOR']['wall_ft'] = {'lf':14,'cf':8,'rf':13}

def hist(k, rows): recs[k]['franchise_history'] = [dict(years=y, name=n, city=c) for y,n,c in rows]
# 2. Franchise history: major-league seasons only, no overlaps.
hist('CWS', [('1901–1903','Chicago White Stockings','Chicago'),('1904–present','Chicago White Sox','Chicago')])
hist('CLE', [('1901','Cleveland Bluebirds','Cleveland'),('1902','Cleveland Broncos','Cleveland'),('1903–1914','Cleveland Naps','Cleveland'),('1915–2021','Cleveland Indians','Cleveland'),('2022–present','Cleveland Guardians','Cleveland')])
hist('MIN', [('1901–1960','Washington Senators (also Nationals)','Washington, D.C.'),('1961–present','Minnesota Twins','Minneapolis')])
hist('BAL', [('1901','Milwaukee Brewers','Milwaukee'),('1902–1953','St. Louis Browns','St. Louis'),('1954–present','Baltimore Orioles','Baltimore')])
hist('CIN', [('1882–1889','Cincinnati Red Stockings','Cincinnati'),('1890–1952','Cincinnati Reds','Cincinnati'),('1953–1958','Cincinnati Redlegs','Cincinnati'),('1959–present','Cincinnati Reds','Cincinnati')])
hist('PIT', [('1882–1886','Allegheny','Pittsburgh'),('1887–1890','Pittsburgh Alleghenys','Pittsburgh'),('1891–present','Pittsburgh Pirates','Pittsburgh')])
# 3. Single-value corrections.
recs['CWS']['pennants'] = 6                      # 1901, 1906, 1917, 1919, 1959, 2005
recs['CHC']['team_founded'] = 1876               # first National League season (club dates to 1870)
recs['CIN']['team_founded'] = 1882               # first major-league season (American Association)
recs['SD']['colors'] = ['#2F241D', '#FFC425']    # brown and gold since 2020
recs['SD']['dimensions_ft']['rf'] = 322          # MLB and Clem agree
recs['ATH']['capacity'] = 14014
recs['ATH']['note'] = "Capacity includes lawn and standing room; fixed seats total 10,624. " + recs['ATH']['note']
recs['LAD']['stadium'] = 'Dodger Stadium'; recs['LAD']['former_names'] = []
recs['LAD']['note'] = "Sources in 2026 list the venue as Uniqlo Field at Dodger Stadium, after a field naming-rights agreement."
recs['WSH']['former_names'] = []
recs['ARI']['previous_stadium'] = ''
recs['TEX']['previous_stadium'] = 'Globe Life Park in Arlington (1994–2019)'
recs['NYM']['notable'] = ["Opened in 2009 next to the site where Shea Stadium once stood.",
    "The Jackie Robinson Rotunda entrance recalls Ebbets Field in Brooklyn.",
    "The Home Run Apple rises beyond center field after Mets home runs.",
    "Hosted the 2013 All-Star Game and three games of the 2015 World Series."]
recs['ATH']['notable'] = recs['ATH']['notable'][:3]

order = {'AL':0,'NL':1}; dv = {'East':0,'Central':1,'West':2}
out = sorted(recs.values(), key=lambda r:(order[r['league']], dv[r['division']], r['team']))
for r in out:
    for k in ('lat','lon','opened','capacity','team_founded'): assert r[k] is not None, (r['id'],k)
    assert r['roof'] in ('open','retractable','fixed'); assert len(r['colors'])==2
    d=r['dimensions_ft']; assert d['lf'] and d['cf'] and d['rf'], r['id']
json.dump(out, open('data/stadiums.json','w'), indent=1, ensure_ascii=False)
open('src/data.js','w').write('// Generated by build-data.py from data/stadiums.json\nexport const STADIUMS = ' + json.dumps(out, ensure_ascii=False) + ';\n')
print(len(out), 'records;', sum(1 for r in out if None in r['wall_ft'].values()), 'with a missing wall height')
